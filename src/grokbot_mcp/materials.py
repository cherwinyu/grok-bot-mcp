"""One rendering path for wizard and migration Routine materials."""
from __future__ import annotations
from importlib.resources import files
from pathlib import Path
from grokbot_mcp import __version__
from grokbot_mcp.identity import TEMPLATE_VERSION
from grokbot_mcp.routine import claim_command, FINGERPRINT_PLACEHOLDER


def ps(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def render_routine(phase: str, *, workspace_root: Path, workspace_id: str,
                   registry: Path, python: Path, mode: str, test_options: dict | None = None,
                   expected_fingerprint: str | None = None) -> str:
    if phase not in {"validate", "execute"} or mode not in {"create", "reuse", "migrate"}:
        raise ValueError("invalid_routine_phase")
    package = files("grokbot_mcp").joinpath("templates")
    text = package.joinpath(phase + ".md").read_text(encoding="utf-8").split("## Local confirmation")[0]
    if mode != "create":
        text = text.replace("Create one long-lived routine", "Use the existing long-lived routine")
        text = text.replace("Create a second long-lived routine.", "Use the existing execute routine; do not create a duplicate.")
    fingerprint = expected_fingerprint or (test_options or {}).get("policy_fingerprint", FINGERPRINT_PLACEHOLDER)
    claim = ("$env:GROKBOT_MCP_REGISTRY = " + ps(str(registry)) + "\n& " + ps(str(python))
             + " -I -X utf8 -m " + claim_command(workspace_id, fingerprint))
    text = text.replace("C:\\ExamplePython\\python.exe -m " + claim_command("example-workspace"), claim)
    text = text.replace("Replace `C:\\ExamplePython\\python.exe` and `example-workspace` with your install and registry id.",
                        "Use the explicit interpreter and registry selected in this packet; use only the received execution ID.")
    text = text.replace("C:\\ExampleWorkspace", str(workspace_root))
    text = text.replace("For the example workspace that command id is `python_unittest`.",
                        "Use the administrator's registered test-command mapping; do not infer a command from this template.")
    writing = package.joinpath("result-writing.md").read_text(encoding="utf-8")
    options = test_options or {}
    required_output = ""
    if phase == "execute" and options.get("require_test_output") is True:
        required_output = ("\n   - Required `tests.output={\"head\",\"tail\",\"truncated\"}`, `tests.output_sha256`, "
                           "and `tests.output_bytes`: capture the complete UTF-8 test output bytes and merge "
                           "`grokbot_mcp.result_contract.output_evidence(raw)` into `tests`. The helper bounds "
                           "head/tail and hashes/counts the full stream, not just the excerpt.\n"
                           "   - If tests could not run, honestly report `status: failed` and `tests.not_run: true` "
                           "(`not_run=true`), with the registered command_id; omit unmeasured counts, exit code "
                           "and output. Never invent output or claim success.\n")
    text = text.replace("{{REQUIRED_TEST_OUTPUT}}", required_output)
    writing = writing.replace("{{REQUIRED_TEST_OUTPUT}}", required_output)
    if options.get("allowed_prefixes") or "prefix_ceiling" in options:
        text = text.replace("Stop if the manifest allow-list is not a subset.",
                            "Check the exact task list against the local registry's file/prefix policy; stop on mismatch.")
        sections = package.joinpath("prefix-policy.md").read_text(encoding="utf-8").split("<!-- prefix-ceiling -->\n")
        text += "\n" + (sections[1] if "prefix_ceiling" in options else sections[0])
    if phase == "execute" and (options.get("require_test_output") or options.get("test_selection") == "reject"
                              or any(c.get("applies_to") is not None or c.get("argv") for c in options.get("test_commands", []))):
        writing += "\n" + package.joinpath("test-evidence.md").read_text(encoding="utf-8")
    substitutions = {"{{PYTHON_PS}}": ps(str(python)), "{{REGISTRY_PS}}": ps(str(registry)),
        "{{ROOT_PS}}": ps(str(workspace_root)), "{{WORKSPACE_PS}}": ps(workspace_id),
        "{{PHASE}}": phase, "{{ID_FIELD}}": "task_id" if phase == "validate" else "execution_id",
        "{{TEMPLATE_VERSION}}": TEMPLATE_VERSION, "{{BRIDGE_VERSION}}": __version__}
    for old, new in substitutions.items():
        writing = writing.replace(old, new)
    return ("<!-- Generated by grokbot-mcp-bridge " + __version__ + "; template " + TEMPLATE_VERSION + " -->\n"
            + text + "\n" + writing + "\n")
